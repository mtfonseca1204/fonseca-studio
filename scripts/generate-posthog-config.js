const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'posthog-config.js');
const envKey = (process.env.POSTHOG_KEY || process.env.NEXT_PUBLIC_POSTHOG_KEY || '').trim();
const apiHost = (process.env.POSTHOG_HOST || 'https://us.i.posthog.com').trim();

let existingKey = '';
try {
    const existing = fs.readFileSync(out, 'utf8');
    const match = existing.match(/"key"\s*:\s*"([^"]*)"/);
    if (match) existingKey = match[1].trim();
} catch {
    // First run — no existing config yet.
}

const key = envKey || existingKey;

const contents = `// Generated by scripts/generate-posthog-config.js — do not edit on deploy.
window.FONSECA_POSTHOG_CONFIG = ${JSON.stringify({ key, api_host: apiHost }, null, 4)};
`;

fs.writeFileSync(out, contents, 'utf8');

if (key.startsWith('phc_')) {
    console.log(envKey ? 'PostHog config written from POSTHOG_KEY.' : 'PostHog config kept existing project key.');
} else {
    console.warn('PostHog key missing. Set POSTHOG_KEY in Vercel or paste phc_ key into posthog-config.js for local tracking.');
}
